//! Canonical JSON and the defensive input hash (Node `engine/hash.ts`).
//!
//! `canonical_json` reproduces `canonicalJson` byte for byte: object keys sorted by UTF-16 code units
//! (JS `Array.prototype.sort` on strings), no whitespace, primitives written as `JSON.stringify` does.
//! `fnv1a` is FNV-1a over the UTF-16 code units of that text: low byte, then high byte, of each unit.
use rust_cli_base::js::json::{js_double, write_str};
use serde_json::Value;

/// Canonical JSON text of `value` (Node `canonicalJson`).
pub fn canonical_json(value: &Value) -> String {
    let mut out = String::new();
    write_canonical(&mut out, value);
    out
}

fn write_canonical(out: &mut String, value: &Value) {
    match value {
        Value::Array(items) => {
            out.push('[');
            for (index, item) in items.iter().enumerate() {
                if index > 0 {
                    out.push(',');
                }
                write_canonical(out, item);
            }
            out.push(']');
        }
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort_by(|a, b| a.encode_utf16().cmp(b.encode_utf16()));
            out.push('{');
            for (index, key) in keys.into_iter().enumerate() {
                if index > 0 {
                    out.push(',');
                }
                write_str(out, key);
                out.push(':');
                if let Some(member) = map.get(key.as_str()) {
                    write_canonical(out, member);
                }
            }
            out.push('}');
        }
        Value::String(text) => write_str(out, text),
        Value::Number(number) => out.push_str(&js_double(number.as_f64().unwrap_or(f64::NAN))),
        Value::Bool(flag) => out.push_str(if *flag { "true" } else { "false" }),
        Value::Null => out.push_str("null"),
    }
}

/// 32-bit FNV-1a over the UTF-16 code units of `input`, as 8 lowercase hex digits (Node `fnv1a`).
pub fn fnv1a(input: &str) -> String {
    let mut hash: u32 = 0x811c_9dc5;
    for unit in input.encode_utf16() {
        hash ^= u32::from(unit & 0xff);
        hash ^= u32::from((unit >> 8) & 0xff);
        hash = hash.wrapping_mul(0x0100_0193);
    }
    format!("{hash:08x}")
}

/// Hash of a host-call input: `fnv1a(canonical_json(value))` (Node `inputHash`).
pub fn input_hash(value: &Value) -> String {
    fnv1a(&canonical_json(value))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn fnv1a_matches_the_offset_basis_and_one_ascii_step() {
        // Empty input is the offset basis; "a" is one XOR and one multiply from it.
        assert_eq!(fnv1a(""), "811c9dc5");
        assert_eq!(fnv1a("a"), "e40c292c");
    }

    #[test]
    fn keys_sort_by_utf16_units_not_code_points() {
        // U+1F600 is the surrogate pair D83D DE00, which sorts before U+E000 in UTF-16 order.
        let value = json!({"\u{e000}": 1, "\u{1f600}": 2, "a": 3});
        assert_eq!(
            canonical_json(&value),
            "{\"a\":3,\"\u{1f600}\":2,\"\u{e000}\":1}"
        );
    }

    /// Node's `canonicalJson` and `inputHash` for each case (generated by
    /// `scripts/rust-cli/workflow-engine-goldens.ts`). Every case is parsed from its JSON text.
    const HASH_GOLDENS: &str = include_str!("../fixtures/hash-goldens.json");

    #[test]
    fn canonical_text_and_hash_match_node_for_every_golden_case() {
        let goldens: Value = serde_json::from_str(HASH_GOLDENS).expect("golden file parses");
        let cases = goldens["cases"].as_array().expect("cases array");
        assert!(cases.len() >= 28);
        for case in cases {
            let text = case["text"].as_str().expect("text");
            let value: Value = serde_json::from_str(text).expect("case parses");
            assert_eq!(
                canonical_json(&value),
                case["canonical"],
                "canonical of {text}"
            );
            assert_eq!(input_hash(&value), case["hash"], "hash of {text}");
        }
    }

    #[test]
    fn numbers_follow_js_number_to_string() {
        assert_eq!(canonical_json(&json!(1.0)), "1");
        assert_eq!(canonical_json(&json!(1e21)), "1e+21");
        assert_eq!(canonical_json(&json!(1e-7)), "1e-7");
        assert_eq!(canonical_json(&json!(-0.0)), "0");
    }
}
