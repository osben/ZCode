function $appendPlainText(text: string) {
  const root = $getRoot();
  const lastChild = root.getLastChild();
  const paragraph = $isParagraphNode(lastChild) ? lastChild : $createParagraphNode();
  if (!$isParagraphNode(lastChild)) {
    root.append(paragraph);
  }

  const currentText = paragraph.getTextContent();
  if (currentText.length > 0 && !/\s$/.test(currentText)) {
    paragraph.append($createTextNode(" "));
  }

  paragraph.append($createTextNode(text));
  paragraph.selectEnd();
}

/**
 * Inserts dictated text at the caret (replacing a selected range), padding with a space only on a
 * side that borders a non-space character. Lexical keeps its last stored selection while the editor
 * is blurred, so inserting after a click on the microphone button is expected to land at the
 * caret; with no stored selection the text is appended to the end like appendText.
 */
export function insertEditorPlainTextAtSelection(editor: LexicalEditor, text: string) {
  editor.update(
    () => {
      const selection = $getSelection();
      if (!$isRangeSelection(selection)) {
        $appendPlainText(text);
        return;
      }
      const [start, end] = selection.isBackward()
        ? [selection.focus, selection.anchor]
        : [selection.anchor, selection.focus];
      const before = $charBeforePoint(start);
      const after = $charAfterPoint(end);
      const leading = before && !/\s/.test(before) ? " " : "";
      const trailing = after && !/\s/.test(after) ? " " : "";
      selection.insertText(`${leading}${text}${trailing}`);
    },
    { tag: PROGRAMMATIC_UPDATE_TAG },
  );
}

function $charBeforePoint(point: PointType): string {
  const node = point.getNode();
  if (point.type === "text") {
    if (point.offset > 0) return node.getTextContent().charAt(point.offset - 1);
    return lastChar(node.getPreviousSibling()?.getTextContent());
  }
  if (!$isElementNode(node)) return "";
  return lastChar(node.getChildAtIndex(point.offset - 1)?.getTextContent());
}

function $charAfterPoint(point: PointType): string {
  const node = point.getNode();
  if (point.type === "text") {
    const content = node.getTextContent();
    if (point.offset < content.length) return content.charAt(point.offset);
    return firstChar(node.getNextSibling()?.getTextContent());
  }
  if (!$isElementNode(node)) return "";
  return firstChar(node.getChildAtIndex(point.offset)?.getTextContent());
}

const lastChar = (text: string | undefined) => (text ? text.charAt(text.length - 1) : "");
const firstChar = (text: string | undefined) => (text ? text.charAt(0) : "");

function getPromptMentionIdAfterDomSelection(rootElement: HTMLElement): string | null {
  const selection = window.getSelection();
  if (!selection?.isCollapsed || !selection.anchorNode) {
    return null;
  }

  const anchorNode = selection.anchorNode;
  if (!rootElement.contains(anchorNode)) {
    return null;
  }

  if (anchorNode.nodeType === Node.ELEMENT_NODE) {
    const child = anchorNode.childNodes.item(selection.anchorOffset);
    return getPromptMentionIdFromBoundaryNode(child);
  }

  if (anchorNode.nodeType !== Node.TEXT_NODE) {
    return null;
  }

  if (selection.anchorOffset !== (anchorNode.textContent ?? "").length) {
    return null;
  }

  return getPromptMentionIdFromBoundaryNode(anchorNode.nextSibling);
}

function getPromptMentionIdFromBoundaryNode(node: Node | null): string | null {
  if (!(node instanceof HTMLElement) || !node.matches("[data-mention-id]")) {
    return null;
  }
  return node.dataset.mentionId ?? null;
}

function selectAfterPromptMentionById(mentionId: string): boolean {
  const mentionNode = $getRoot()
    .getAllTextNodes()
    .find(
      (node): node is PromptMentionNode =>
        $isPromptMentionNode(node) && node.getMention().id === mentionId,
    );
  if (!mentionNode) {
    return false;
  }

  const nextSibling = mentionNode.getNextSibling();
  if ($isTextNode(nextSibling)) {
    const text = nextSibling.getTextContent();
    const offset = /^\s/.test(text) ? Math.min(1, text.length) : 0;
    nextSibling.select(offset, offset);
    return true;
  }

  mentionNode.selectNext(0, 0);
  return true;
}

/**
 * Keyboard behavior plugin: Enter sends; Shift+Enter inserts a newline.
 *
 * Intercept Enter with COMMAND_PRIORITY_HIGH to prevent Lexical's default paragraph insertion behavior.
 */
function KeyboardPlugin({
  onSubmit,
  onModifiedSubmit,
  onSubmitBlocked,
  disabled,
  submitDisabled,
  allowSubmitWhenEmpty,
  enterSubmits,
}: {
  onSubmit: (text: string) => LexicalSubmitResult;
  onModifiedSubmit?: (text: string) => LexicalSubmitResult;
  onSubmitBlocked?: () => void;
  disabled?: boolean;
  submitDisabled?: boolean;
  allowSubmitWhenEmpty?: boolean;
  enterSubmits: boolean;
}) {
  const [editor] = useLexicalComposerContext();
  // Scoped rebinding layer: read the active composer-command slice; pass it through a ref to avoid re-registering the keyboard listener.
  const effectiveShortcutBindings = useEffectiveShortcutBindings();
  const composerEffectiveRef = useRef({
    composerSend: effectiveShortcutBindings.composerSend ?? [],
    composerInsertNewline: effectiveShortcutBindings.composerInsertNewline ?? [],
  });
  composerEffectiveRef.current = {
    composerSend: effectiveShortcutBindings.composerSend ?? [],
    composerInsertNewline: effectiveShortcutBindings.composerInsertNewline ?? [],
  };

  useEffect(() => {
    const unregisterEnter = editor.registerCommand(
      KEY_ENTER_COMMAND,
      (event: KeyboardEvent | null) => {
        if (!event) return false;

        if (disabled) {
          event.preventDefault();
          return true;
        }

        // Do not intercept while an IME is composing (for example, a Chinese IME).
        if (event.isComposing) {
          return false;
        }

        const text = getEditorMarkdown(editor.getEditorState());

        // Scoped rebinding layer: user key bindings take precedence over built-in defaults.
        // A newline match lets Lexical insert a paragraph; a send match follows the same gates as the main path.
        // With no match, fall through to the main path below (including reverse delivery, modified-key newlines, and viewport gating).
        const composerEffective = composerEffectiveRef.current;
        const scopedAction = resolveComposerKeyAction(event, composerEffective);
        if (scopedAction === "newline") {
          return false;
        }
        if (scopedAction === "send") {
          const modifiedScopedEnter = event.shiftKey || event.ctrlKey || event.metaKey;
          // When reverse delivery is enabled, let the main path handle modified shortcuts (Ctrl+Enter = reverse delivery, whose delivery meaning is more specific than a binding).
          if (!(modifiedScopedEnter && onModifiedSubmit)) {
            // Apply the same gates as bare Enter on the main path: unmodified Enter respects submitDisabled/mobile enterSubmits;
            // modified combinations bypass viewport gating, matching the main path's onModifiedSubmit behavior.
            if (submitDisabled || (!modifiedScopedEnter && !enterSubmits)) {
              return false;
            }
            event.preventDefault();
            if (
              shouldSubmitLexicalEnter({
                allowSubmitWhenEmpty,
                enterSubmits: modifiedScopedEnter ? true : enterSubmits,
                text,
              })
            ) {
              const submitResult = onSubmit(text);
              if (shouldResetLexicalEditorAfterSubmit(submitResult)) {
                resetEditor(editor);
              }
            }
            return true;
          }
        }

        // Main-path precheck: when composerSend has been rebound (the active binding excludes bare Enter),
        // bare Enter no longer means send. Allow Lexical to insert a newline (the expected behavior after rebinding for “Ctrl+Enter users”).
        if (
          !event.shiftKey &&
          !event.ctrlKey &&
          !event.metaKey &&
          shouldBareEnterFallThroughToNewline(composerEffective)
        ) {
          return false;
        }

        if (
          !submitDisabled &&
          onModifiedSubmit &&
          shouldSubmitLexicalModifiedEnter({
            allowSubmitWhenEmpty,
            ctrlKey: event.ctrlKey,
            metaKey: event.metaKey,
            modifiedEnterSubmits: true,
            shiftKey: event.shiftKey,
            text,
          })
        ) {
          event.preventDefault();
          const submitResult = onModifiedSubmit(text);
          if (shouldResetLexicalEditorAfterSubmit(submitResult)) {
            resetEditor(editor);
          }
          return true;
        }

        // Shift+Enter and Ctrl/Meta+Enter when reverse delivery is disabled continue to insert newlines.
        if (event.shiftKey || event.ctrlKey || event.metaKey) {
          return false;
        }

        // While a request is in progress, the user may keep editing the draft but cannot submit again.
        // Mapping this state directly to disabled also disabled typing and suggestions; removing disabled alone
        // would let Enter submit and clear the draft. When submitDisabled, return Enter to Lexical for newline handling.
        // A caller that names the blocked state (for example an unresolved stored model) takes the Enter:
        // the draft stays, no newline is inserted, and the caller shows the reason. Other blocked states keep
        // returning Enter to Lexical, unchanged.
        if (submitDisabled && enterSubmits && onSubmitBlocked) {
          event.preventDefault();
          onSubmitBlocked();
          return true;
        }
        if (submitDisabled || !enterSubmits) {
          return false;
        }

        event.preventDefault();

        if (
          shouldSubmitLexicalEnter({
            allowSubmitWhenEmpty,
            enterSubmits,
            text,
          })
        ) {
          const submitResult = onSubmit(text);
          // The business layer may reject this submission and keep the draft in the input.
          // The Enter handler must not reset unconditionally, or it would discard user input even when nothing was sent.
          if (shouldResetLexicalEditorAfterSubmit(submitResult)) {
            resetEditor(editor);
          }
        }
        return true;
      },
      COMMAND_PRIORITY_HIGH,
    );

    const unregisterBackspace = editor.registerCommand(
      KEY_BACKSPACE_COMMAND,
      (event: KeyboardEvent | null) => {
        const selection = $getSelection();
        if (!$isRangeSelection(selection) || !selection.isCollapsed()) {
          return false;
        }

        const anchor = selection.anchor;
        if (anchor.type !== "text") {
          return false;
        }

        const node = anchor.getNode();
        if (!$isTextNode(node)) {
          return false;
        }

        const text = node.getTextContent();
        if (anchor.offset !== 1 || text !== " ") {
          return false;
        }

        const previousSibling = node.getPreviousSibling();
        if (!$isPromptMentionNode(previousSibling)) {
          return false;
        }

        // Inserting a mention automatically adds a space so the user can continue typing.
        // Previously Backspace removed the space first and then the token, making it feel like the tag took two presses to delete.
        // When the cursor is just after the added space, delete the space and mention token together.
        event?.preventDefault();
        previousSibling.remove();
        node.remove();
        node.getParent()?.selectEnd();
        return true;
      },
      COMMAND_PRIORITY_HIGH,
    );

    const handleRootKeyDownCapture = (event: KeyboardEvent) => {
      if (
        disabled ||
        event.key !== "ArrowRight" ||
        !event.altKey ||
        event.shiftKey ||
        event.ctrlKey ||
        event.metaKey ||
        event.isComposing
      ) {
        return;
      }

      const rootElement = editor.getRootElement();
      if (!rootElement) {
        return;
      }

      const mentionId = getPromptMentionIdAfterDomSelection(rootElement);
      if (!mentionId) {
        return;
      }

      // macOS Option+ArrowRight moves by words in DOM text and previously placed the cursor inside
      // a mention token's filename. On the next keystroke, Lexical then deleted the token as replaced content.
      // At the token's left boundary, move the selection explicitly to its right side to preserve atomic mention editing.
      event.preventDefault();
      event.stopImmediatePropagation();
      editor.update(
        () => {
          selectAfterPromptMentionById(mentionId);
        },
        { tag: PROGRAMMATIC_UPDATE_TAG },
      );
    };

    // Scoped rebinding for non-Enter keys (uniformly enabled): KEY_ENTER_COMMAND dispatches only Enter.
    // When send/newline is bound to a non-Enter key (such as F9), dispatch it from root keydown capture;
    // otherwise rebinding would be inert, and falling back to newline on bare Enter would remove keyboard sending.
    // Physical non-Enter keys cannot be accidentally sent by a mobile soft keyboard, so send bypasses enterSubmits viewport gating.
    // This does not overlap with reverse delivery (Ctrl/Meta+Enter only), so no yielding is needed.
    const handleNonEnterScopedKeydown = (event: KeyboardEvent) => {
      if (disabled || event.repeat || event.isComposing || event.key === "Enter") {
        return;
      }
      const scopedAction = resolveComposerKeyAction(event, composerEffectiveRef.current);
      if (!scopedAction) {
        return;
      }
      if (scopedAction === "newline") {
        event.preventDefault();
        editor.update(() => {
          const selection = $getSelection();
          if ($isRangeSelection(selection)) {
            selection.insertLineBreak();
          }
        });
        return;
      }
      if (submitDisabled) {
        return;
      }
      event.preventDefault();
      const text = getEditorMarkdown(editor.getEditorState());
      if (shouldSubmitLexicalEnter({ allowSubmitWhenEmpty, enterSubmits: true, text })) {
        const submitResult = onSubmit(text);
        if (shouldResetLexicalEditorAfterSubmit(submitResult)) {
          resetEditor(editor);
        }
      }
    };

    const unregisterRootListener = editor.registerRootListener(
      (rootElement, previousRootElement) => {
        previousRootElement?.removeEventListener("keydown", handleRootKeyDownCapture, {
          capture: true,
        });
        rootElement?.addEventListener("keydown", handleRootKeyDownCapture, {
          capture: true,
        });
        previousRootElement?.removeEventListener("keydown", handleNonEnterScopedKeydown, {
          capture: true,
        });
        rootElement?.addEventListener("keydown", handleNonEnterScopedKeydown, {
          capture: true,
        });
      },
    );

    return () => {
      unregisterEnter();
      unregisterBackspace();
      unregisterRootListener();
      editor.getRootElement()?.removeEventListener("keydown", handleRootKeyDownCapture, {
        capture: true,
      });
      editor.getRootElement()?.removeEventListener("keydown", handleNonEnterScopedKeydown, {
        capture: true,
      });
    };
  }, [
    allowSubmitWhenEmpty,
    disabled,
    editor,
    enterSubmits,
    onModifiedSubmit,
    onSubmit,
    onSubmitBlocked,
    submitDisabled,
  ]);

  return null;
}

/**
 * True when an editor update came from the app rather than from typing: programmatic writes
 * (clear, restore, replace) and prompt-history recall. The history tag is separate from the
 * generic one for the slash panel, so it is folded in here; the slash filter keeps reading it as is.
 */
export function isProgrammaticEditorUpdate(tags: ReadonlySet<string>): boolean {
  return tags.has(PROGRAMMATIC_UPDATE_TAG) || tags.has(HISTORY_NAVIGATION_UPDATE_TAG);
}

/**
 * Text-change plugin.
 *
 * With Lexical's built-in OnChangePlugin, the first character typed into an empty editor is skipped by its
 * internal `prevEditorState.isEmpty()` check. The parent input state misses that character, desynchronizing
 * the send button and editor contents. Listen for updates directly and sync only when serialized markdown
 * actually changes so the first character is reported reliably.
 */
function TextContentPlugin({
  onChange,
  taskId,
}: {
  onChange?: (text: string, meta: { programmatic: boolean }) => void;
  taskId?: string | null;
}) {
  const [editor] = useLexicalComposerContext();
  // IME composition flag: do not rely directly on editor.isComposing(), because whether it has been updated
  // when the update listener runs synchronously is timing-dependent. Missing true would misreport the high
  // latency of composing long Chinese/Japanese text as typing lag. Maintain the flag from compositionstart/compositionend instead.
  const composingRef = useRef(false);

  useEffect(() => {
    const handleCompositionStart = () => {
      composingRef.current = true;
    };
    const handleCompositionEnd = () => {
      // compositionend fires just after composition, but the update listener for the committed text usually
      // runs synchronously in the same task. Setting false immediately would misclassify its latency as typing lag.
      // Defer clearing the flag with queueMicrotask so that commit is still skipped as composition, then resume normal measurement.
      queueMicrotask(() => {
        composingRef.current = false;
      });
    };

    // The root may remount; use registerRootListener to detach from the old root and attach to the new one.
    return editor.registerRootListener((rootElement, previousRootElement) => {
      previousRootElement?.removeEventListener("compositionstart", handleCompositionStart);
      previousRootElement?.removeEventListener("compositionend", handleCompositionEnd);
      rootElement?.addEventListener("compositionstart", handleCompositionStart);
      rootElement?.addEventListener("compositionend", handleCompositionEnd);
    });
  }, [editor]);

  useEffect(() => {
    if (!onChange) {
      return;
    }

    const readEditorMarkdown = createCachedEditorMarkdownReader();
    return editor.registerUpdateListener(
      ({ dirtyElements, dirtyLeaves, editorState, prevEditorState, tags }) => {
        if (dirtyElements.size === 0 && dirtyLeaves.size === 0) {
          return;
        }

        // Typing-lag timing covers the hot path of full serialization plus synchronous onChange rerendering.
        const startedAt = performance.now();

        const nextText = readEditorMarkdown(editorState);
        const previousText = readEditorMarkdown(prevEditorState);
        if (nextText === previousText) {
          return;
        }

        // Consumers that must tell typing from the app's own writes (clears, restores, history recall)
        // read this flag.
        onChange(nextText, { programmatic: isProgrammaticEditorUpdate(tags) });

        const lagMs = performance.now() - startedAt;
        // Programmatic edits and IME composition do not count as typing lag (recordInputLag filters them centrally).
        recordInputLag({
          lagMs,
          textLength: nextText.length,
          isProgrammatic: tags.has(PROGRAMMATIC_UPDATE_TAG),
          isComposing: composingRef.current,
          taskId: taskId ?? undefined,
        });
      },
    );
  }, [editor, onChange, taskId]);

  return null;
}

