  placeholder,
  disabled = false,
  submitDisabled = false,
  onSubmitBlocked,
  allowSubmitWhenEmpty = false,
  enterSubmits = true,
  onSubmit,
  onModifiedSubmit,
  onChange,
  onFocus,
  triggerPanelContainer,
