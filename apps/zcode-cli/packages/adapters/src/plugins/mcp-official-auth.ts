/*
 * Strict parsing and provenance generation for `auth: { type: "zcode_official" }` in a Plugin `.mcp.json`.
 *
 * Kept in a separate file rather than mcp.ts: official-auth parsing covers both http and stdio transports and is
 * independent of template-variable and transport-field parsing. Keeping it together would further grow mcp.ts,
 * which has already reached its max-lines limit.
 */
import type { McpOfficialProvenance, ZCodeOfficialMcpAuthConfig } from "@zcode/contracts";

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/**
 * Strictly parse `auth`. Return undefined when it is absent (use the regular MCP path); throw when it is present
 * but malformed. Do not silently fall back, which could make a config that appears to use official auth send
 * anonymous requests.
 */
export function parseZCodeOfficialAuth(
  value: unknown,
  mcpKey: string,
): ZCodeOfficialMcpAuthConfig | undefined {
  if (value === undefined) return undefined;
  if (!isRecord(value)) {
    throw new Error(`MCP server ${mcpKey}: auth must be an object`);
  }
  // Match the exact, case-sensitive value; reject aliases such as zcode-official and
  // zcode_official_auth.
  if (value.type !== "zcode_official") {
    throw new Error(`MCP server ${mcpKey}: unsupported auth type: ${String(value.type)}`);
  }
  if (value.provider !== "jwt_token") {
    throw new Error(`MCP server ${mcpKey}: unsupported auth provider: ${String(value.provider)}`);
  }
  return { type: "zcode_official", provider: "jwt_token" };
}

/**
 * Runtime provenance generated by the host. It overrides even an `official` field in `.mcp.json`:
 * a plugin being reviewed cannot declare itself official.
 */
export function buildOfficialProvenance(identity: {
  mcpKey: string;
  pluginId: string;
}): McpOfficialProvenance {
  return { mcpKey: identity.mcpKey, pluginId: identity.pluginId, source: "plugin" };
}
