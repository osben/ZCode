/**
 * Hidden command `__zcode-dwf-child <entry path>`: sandbox child-process entry point for dynamic workflows.
 *
 * Why it exists: a single-file SEA binary does **not parse Node CLI flags**. Flags from
 * the harness default `node --max-old-space-size=… <entry>` would reach the CLI's strict
 * parseArgs unchanged, causing the child process to exit with an error and every
 * workflow run under SEA to fail. The fix mirrors the official plugin host
 * (`plugin-host-command.ts`): under SEA, bootstrap asks the harness to re-execute this
 * binary with the subcommand, and `run.ts` dispatches here **before** parseArgs.
 *
 * Do not pass payload through argv (Windows command-line limit is 32,767 characters).
 * The harness writes a self-contained entry file at
 * `<cwd>/.zcode/workflow-runs/<runId>.mjs`; the final argv item is only its path. The
 * entry file contains childMain and the payload. This module only `import()`s it and
 * injects the CLI process's vm/readline/stdio into its exported `start`, so this module
 * **no longer depends on `@zcode/dynamic-workflow-runtime`**. Best-effort heap-limit
 * `v8.setFlagsFromString` also moved into the entry file with the payload.
 */

import { resolve } from "node:path";
import { createInterface } from "node:readline";
import { pathToFileURL } from "node:url";
import { createContext, runInContext } from "node:vm";
import { ZCODE_DWF_CHILD_COMMAND } from "@zcode/contracts";
import type { RunContext } from "@zcode/shared-types";

export function isDwfChildInvocation(argv: readonly string[]): boolean {
  return argv[0] === ZCODE_DWF_CHILD_COMMAND;
}

/** Entry-file exports (generated by `renderChildEntry` in child-source.ts). */
interface ChildEntryModule {
  start?: (deps: {
    vm: { createContext: typeof createContext; runInContext: typeof runInContext };
    createInterface: typeof createInterface;
    stdin: NodeJS.ReadableStream;
    stdout: { write(chunk: string): unknown };
  }) => Promise<void>;
}

/**
 * Run the sandbox child process until the script terminates. `argv` contains arguments
 * remaining after the subcommand, with the entry-file path as the **last item**.
 *
 * Wait until termination before returning: after `run()` returns, the CLI entry starts a
 * 1-second exit watchdog (`scheduleCliExitWatchdog` in shutdown.ts). Returning early
 * would let the watchdog kill the child just as the run begins.
 */
export async function runDwfChildCommand(ctx: RunContext, argv: string[]): Promise<number> {
  const entryPath = argv[argv.length - 1];
  if (argv.length === 0 || entryPath === undefined) {
    ctx.stderr.write(`Usage: ${ZCODE_DWF_CHILD_COMMAND} <entry path>\n`);
    return 1;
  }

  try {
    // Dynamically import an ESM file from disk (same as plugin-host-command.ts loading a
    // plugin entry). The entry file sees that it is not the process entry (argv[1] is the
    // subcommand, not its own path), so it does not start itself; call start here.
    const entry = (await import(pathToFileURL(resolve(entryPath)).href)) as ChildEntryModule;
    if (typeof entry.start !== "function") {
      throw new Error(`workflow entry file exports no start(): ${entryPath}`);
    }
    await entry.start({
      vm: { createContext, runInContext },
      createInterface,
      stdin: ctx.stdin,
      stdout: ctx.stdout,
    });
    return 0;
  } catch (error) {
    // stdout is the parent's NDJSON channel, so send diagnostics only to stderr. The
    // harness uses child-process stderr to attribute “exited without completing” failures
    // (`child.on("close")` in harness.ts).
    const message = error instanceof Error ? error.message : String(error);
    ctx.stderr.write(`Workflow child failed: ${message}\n`);
    return 1;
  }
}
