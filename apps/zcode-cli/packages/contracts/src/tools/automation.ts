/**
 * Contract-layer mirror schema for custom repeat rules (zod v3).
 * Keep its structure in sync with @zcode/shared's ZCodeAutomationScheduleRule. Do not import
 * shared here, to avoid coupling agent contracts' zod v3 to shared's zod v4 (same mirror
 * convention as browser-control).
 * Retain cronExpr for compatibility display; this field is authoritative for scheduling. The
 * session-side long-interval carrier is normalized into this field.
 */
export const CronAutomationScheduleRuleSchema = z
  .object({
    unit: z.enum(["minute", "hourly", "daily", "weekly", "monthly", "yearly"]),
    interval: z.number().int().positive(),
    hour: z.number().int().min(0).max(23),
    minute: z.number().int().min(0).max(59),
    anchorAt: z.number().int(),
    weekdays: z.array(z.number().int().min(0).max(6)).optional(),
    monthDays: z.array(z.number().int().min(1).max(31)).optional(),
    /** For yearly rules: human month, 1-12. Defaults to the month in anchorAt (compatible with older records that omit this field). */
    months: z.array(z.number().int().min(1).max(12)).optional(),
    monthlyMode: z.enum(["date", "weekday"]).optional(),
  })
  .strict();
export type CronAutomationScheduleRule = z.infer<typeof CronAutomationScheduleRuleSchema>;

export const CronAutomationSchema = z
  .object({
    automationId: nonEmptyString,
    title: z.string(),
    cronExpr: nonEmptyString,
    prompt: nonEmptyString,
    enabled: z.boolean(),
    lifecycleStatus: z.enum(["active", "completed", "failed", "paused"]),
    nextRunAt: z.number().int().nonnegative().optional(),
    lastRunAt: z.number().int().nonnegative().optional(),
    runCount: z.number().int().nonnegative(),
    recurring: z.boolean(),
    maxRuns: z.number().int().positive().optional(),
    modelSelection: cronModelSelectionSchema.optional(),
    mode: z.enum(["build", "edit", "plan", "yolo", "guarded"]).optional(),
    // Custom repeat rule; when absent, scheduling falls back to parsing cronExpr. Session cards
    // need this field to display real intervals cron cannot express (such as every 50 hours or
    // every 40 days, where the compatibility cronExpr is only 0 * * * *).
    scheduleRule: CronAutomationScheduleRuleSchema.optional(),
  })
  .strict();
export type CronAutomation = z.infer<typeof CronAutomationSchema>;

