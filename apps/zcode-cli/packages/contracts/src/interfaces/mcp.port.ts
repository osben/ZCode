export interface McpToolDescriptor {
  serverName: string;
  toolName: string;
  name?: string;
  description?: string;
  timeoutMs?: number;
  inputSchema: JsonSchema;
  outputSchema?: JsonSchema;
  annotations?: McpToolAnnotations;
  /**
   * This tool's result is **trusted enough to change the UI**: it came from an MCP server with
   * `type: "http"` and `auth.type = zcode_official`.
   *
   * Used only to trust structured result identifiers (`error_code` for exhausted quota / missing
   * plan). The criterion is "who produced the result," not "who the plugin is":
   * - http: the response comes from the ZCode backend. A live connection means each request passed
   *   origin validation and failed closed; even a third-party plugin declaring official auth can only
   *   send requests to real ZCode and cannot write the response body.
   * - stdio: the plugin process produces the result and can forge it, so this flag is **not set**.
   *
   * Intentionally **not** based on whether the plugin came from the official marketplace: that would
   * break official plugins installed from other sources (including local testing and
   * zcode-plugins-test), and would not be a real security barrier—see `isOfficialMcpOriginTrusted` in
   * `@zcode/shared`.
   */
  official?: boolean;
}

export type McpContentBlock = Record<string, unknown>;

export interface McpToolCallResult {
  content: McpContentBlock[];
  structuredContent?: unknown;
  isError?: boolean;
  _meta?: Record<string, unknown>;
}

export interface McpConnectionSnapshot {
  statuses: Record<string, McpServerStatus>;
  tools: McpToolDescriptor[];
}

export interface McpConnectOptions {
  /**
   * Maximum wait for the authorization_code OAuth callback.
   * The regular MCP timeoutMs applies only to protocol requests; session startup needs a separate
   * limit for waiting on OAuth authorization.
   */
  oauthAuthorizationTimeoutMs?: number;
  /**
   * Check that an existing connection is alive before reusing it (see McpPort.pingServer); reconnect
   * if it has died. Calls where the user explicitly requests a new check, such as refreshing the
   * settings page, must set this flag; session startup need not, and can reuse a recently established
   * pooled connection.
   */
  revalidate?: boolean;
  signal?: AbortSignal;
  trace?: TraceContext;
  workingDirectory?: string;
  /** Use workspaceIdentity for identity isolation; fall back to workingDirectory only when unavailable locally. */
  workspaceIdentity?: string;
}

export interface McpCallToolRequest {
  serverName: string;
  toolName: string;
  arguments?: Record<string, unknown>;
  trace?: TraceContext;
  /** Call origin; host MCP can use this to restrict capabilities that cannot safely be inherited by subagents. */
  runtimeScope?: "main" | "subagent";
  /** Request context is used only for shared-host isolation and does not change MCP tool parameters. */
  workspacePath?: string;
  workspaceIdentity?: string;
  workspaceKey?: string;
  remoteSessionId?: string;
  clientMode?: string;
  deliveryKind?: string;
  turnId?: string;
}

export interface McpCallToolOptions {
  signal?: AbortSignal;
  timeoutMs?: number;
}

/**
 * Port-level failure categories (cases where no request is sent).
 * `official_mcp_origin_untrusted` may come from local adapter validation or the host's second validation.
 */
export type OfficialMcpAuthFailureReason = OfficialMcpAuthPortFailureReason;

export type OfficialMcpAuthHeadersResult =
  | { ok: true; headers: Record<string, string> }
  | { ok: false; reason: OfficialMcpAuthFailureReason };

/**
 * Dependency-injection port through which the MCP adapter obtains identity headers.
 * The adapter does not depend directly on `packages/services`; the Agent process uses this port to
 * request identity headers for the current request from the host.
 *
 * Failures must use return values rather than exceptions; callers must not parse reasons from error text.
 * `workspaceIdentity` / `workspacePath` / `pluginId` / `mcpKey` / `targetOrigin`
 * Used only for routing, secondary validation, and auditing; **not for credential selection**—credentials are host-global state.
 */
export interface OfficialMcpAuthHeadersPort {
  resolveHeaders(input: {
    pluginId: string;
    mcpKey: string;
    targetOrigin: string;
    workspaceIdentity?: string;
    workspacePath?: string;
    signal?: AbortSignal;
  }): Promise<OfficialMcpAuthHeadersResult>;
}

/**
 * Official MCP trust decision.
 *
 * One rule: **the target origin must exactly match the current ZCode API origin (HTTPS, no
 * username/password)**, with a local-test switch that permits only HTTP loopback. `pluginId` / `mcpKey`
 * are passed only for logging and credential-resolution ownership; they **do not affect the result**.
 * The former "must be an official marketplace plugin" check was removed in 2026-08 (it prevented
 * official plugins from testing against the real endpoint before release, while third-party plugins
 * could read the same credentials through a hook, so it was not a real barrier).
 *
 * Implemented in `@zcode/shared` and shared by host and adapter to prevent one side from accepting an
 * origin that the other rejects. It is asynchronous so the host can resolve an origin overridden by
 * settings.
 */
export interface OfficialMcpTrustedOriginRegistry {
  isTrusted(input: { pluginId: string; mcpKey: string; origin: string }): Promise<{
    detail?: string;
    trusted: boolean;
  }>;
}

export interface McpPort {
  connectConfiguredServers(
    servers: Record<string, McpServerConfig>,
    options?: McpConnectOptions,
  ): Promise<McpConnectionSnapshot>;
  connectServer(
    name: string,
    config: McpServerConfig,
    options?: McpConnectOptions,
  ): Promise<McpServerStatus>;
  disconnectServer(name: string): Promise<McpServerStatus | undefined>;
  /**
   * Actively check whether the connection is still alive; returns false if the transport is disconnected.
   * Stopping an HTTP/SSE MCP does not dispatch onclose, so status() may remain connected indefinitely;
   * only an explicit ping reveals this "silent death." Optional implementation: callers treat the
   * connection as alive when this method is unavailable.
   */
  pingServer?(name: string, options?: { timeoutMs?: number }): Promise<boolean>;
  status(): Promise<Record<string, McpServerStatus>>;
  listTools(): Promise<McpToolDescriptor[]>;
  callTool(request: McpCallToolRequest, options?: McpCallToolOptions): Promise<McpToolCallResult>;
  close(): Promise<void>;
}
