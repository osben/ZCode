export interface McpToolDescriptor {
  serverName: string;
  toolName: string;
  name?: string;
  description?: string;
  timeoutMs?: number;
  inputSchema: JsonSchema;
  outputSchema?: JsonSchema;
  annotations?: McpToolAnnotations;
  /**
   * This tool's result is **trusted enough to change the UI**: it came from an MCP server with
   * `type: "http"` and `auth.type = zcode_official`.
   *
   * Used only to trust structured result identifiers (`error_code` for exhausted quota / missing
   * plan). The criterion is "who produced the result," not "who the plugin is":
   * - http: the response comes from the ZCode backend. A live connection means each request passed
   *   origin validation and failed closed; even a third-party plugin declaring official auth can only
   *   send requests to real ZCode and cannot write the response body.
   * - stdio: the plugin process produces the result and can forge it, so this flag is **not set**.
   *
   * Intentionally **not** based on whether the plugin came from the official marketplace: that would
   * break official plugins installed from other sources (including local testing and
   * zcode-plugins-test), and would not be a real security barrier—see `isOfficialMcpOriginTrusted` in
   * `@zcode/shared`.
   */
  official?: boolean;
  /**
   * Which callers may use the tool (`_meta.ui.visibility`, defaulting to `["model", "app"]`),
   * independent of whether the tool has UI resources. Tools without "model" are excluded from provider
   * contracts; tools without "app" reject `mcp/uiCallTool`. Set by the adapter after normalization;
   * for older descriptors, fall back to `ui.visibility`, then default to visible to both.
   */
  visibility?: McpAppsToolVisibility[];
  /**
   * Normalized plugin-UI presentation descriptor from the tool's `_meta`.
   * Present only for tools that declare a valid `ui://` resourceUri; its visibility comes from the same source as the field above.
   */
  ui?: McpToolUiDescriptor;
}

/** Sole visibility resolver: descriptor.visibility → ui.visibility → visible to both. */
export function resolveMcpToolVisibility(
  descriptor: Pick<McpToolDescriptor, "visibility" | "ui">,
): McpAppsToolVisibility[] {
  return descriptor.visibility ?? descriptor.ui?.visibility ?? ["model", "app"];
}

