/**
 * Authentication declaration for the official ZCode Server MCP.
 * Allowed with `type: "http"` and `type: "stdio"`; `sse` remains rejected.
 * `type` / `provider` must be exact values; aliases and case variants are not accepted.
 *
 * Note: this field alone does **not** prove official identity. Official identity is determined by the
 * ZCode API origin resolved at runtime (and checked again by the host); a third-party plugin copying
 * this field can only direct credentials to the real ZCode backend.
 *
 * The two transports deliver credentials differently:
 * - http: the host injects identity headers per request in the fetch wrapper; credentials never enter the plugin process;
 * - stdio: the plugin process sends requests itself, and identity headers are sent in `_meta` on each outbound protocol message.
 */
export interface ZCodeOfficialMcpAuthConfig {
  type: "zcode_official";
  provider: "jwt_token";
}

/**
 * Runtime ownership metadata generated by the Plugin loader; `.mcp.json` cannot override it.
 * Used for credential resolution and log correlation, not trust decisions.
 * The target origin must pass `isOfficialMcpOriginTrusted`; plugin identity itself is not an
 * authorization filter. Destination validation, server API permissions, plans, and quotas enforce
 * separate boundaries.
 */
export interface McpOfficialProvenance {
  pluginId: string;
  /** Original MCP key within the Plugin (before the `plugin:<name>:` namespace prefix is added). */
  mcpKey: string;
  source: "plugin";
}

